#!/usr/bin/env python3
"""Generate Sources/VitCore/WidthTable.swift from Python's unicodedata.

Width rules:
  0 -> combining marks (Mn, Me), format chars (Cf, except U+00AD),
       Hangul medial/final jamo (U+1160-11FF), U+200B
  2 -> East Asian Width W or F (includes Emoji_Presentation since Unicode 9)
  1 -> everything else
"""
import unicodedata, sys, os

def width(cp):
    if cp == 0xAD:
        return 1
    if 0x1160 <= cp <= 0x11FF or cp == 0x200B:
        return 0
    c = chr(cp)
    cat = unicodedata.category(c)
    if cat in ("Mn", "Me", "Cf"):
        return 0
    if unicodedata.east_asian_width(c) in ("W", "F"):
        return 2
    # Unassigned code points in the wide CJK planes are wide too.
    if cat == "Cn" and (0x20000 <= cp <= 0x2FFFD or 0x30000 <= cp <= 0x3FFFD):
        return 2
    return 1

ranges = []
start, cur = 0x80, width(0x80)
for cp in range(0x81, 0x110000):
    w = width(cp)
    if w != cur:
        if cur != 1:
            ranges.append((start, cp - 1, cur))
        start, cur = cp, w
if cur != 1:
    ranges.append((start, 0x10FFFF, cur))

out = os.path.join(os.path.dirname(__file__), "..", "Sources", "VitCore", "WidthTable.swift")
with open(out, "w") as f:
    f.write("// Generated by scripts/gen_width.py (Unicode %s). Do not edit.\n" % unicodedata.unidata_version)
    f.write("// Flat triples: (first, last, width) for every range whose width is not 1.\n")
    f.write("let widthRanges: [UInt32] = [\n")
    for a, b, w in ranges:
        f.write("    0x%X, 0x%X, %d,\n" % (a, b, w))
    f.write("]\n")
print(len(ranges), "ranges written to", os.path.normpath(out))
